#!/usr/bin/env python3
"""Fresh three-arm comparison of native Codex, deployed pi-rs, and official RTK hooks."""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import shutil
import sqlite3
import subprocess
import tempfile
import time

import run


RTK_BINARY = Path('/tmp/pi-rs-rtk-0.51.0/rtk')
RTK_SOURCE = Path('/tmp/pi-rs-rtk-upstream')
SHARE_DIRECTORY = Path('/home/aragao/.local/share')
CONFIG_DIRECTORY = Path('/home/aragao/.config')
MODEL = 'gpt-6.1-sol'
EFFORT = 'medium'
ARMS = ('stock', 'pi', 'rtk')
COMMON_PROMPT = run.COMMON_PROMPT.replace(
    'except recovery output files generated by your own commands.',
    'except installed agent instruction documents and recovery output files generated by your own commands.')


def environment(pi_binary: Path | None = None, toolchain_bin: Path | None = None) -> dict:
    env = {k: v for k, v in os.environ.items()
           if not k.startswith(('CODEX_', 'NOISE_', 'OPENAI_', 'RTK_')) or k == 'CODEX_HOME'}
    selected_pi = pi_binary or run.PI_BINARY
    prefixes = [str(RTK_BINARY.parent), str(selected_pi.parent)]
    if toolchain_bin:
        prefixes.append(str(toolchain_bin))
    env.update(PATH=':'.join(prefixes) + ':' + env['PATH'],
               RUST_LOG='error', GIT_TERMINAL_PROMPT='0', CARGO_NET_OFFLINE='true',
               RTK_TELEMETRY_DISABLED='1', RTK_HOOK_AUDIT='1')
    return env


def mounts(session: Path) -> list[str]:
    return ['bwrap', '--die-with-parent', '--ro-bind', '/', '/', '--bind', '/tmp', '/tmp',
            '--proc', '/proc', '--dev-bind', '/dev', '/dev',
            '--bind', str(session / 'codex-state'), str(run.CODEX_DIRECTORY),
            '--bind', str(session / 'share-state'), str(SHARE_DIRECTORY),
            '--bind', str(session / 'config-state'), str(CONFIG_DIRECTORY), '--']


def setup(session: Path, arm: str, guidance: bytes, env: dict | None = None) -> dict:
    for p in ('codex-state', 'share-state/pi-rs', 'share-state/rtk', 'config-state/rtk'):
        (session / p).mkdir(parents=True, exist_ok=True)
    if arm == 'pi':
        run.write(session / 'codex-state/AGENTS.md', guidance)
    elif arm == 'rtk':
        proc = subprocess.run(mounts(session) + [str(RTK_BINARY), 'init', '-g', '--codex',
                                              '--no-trust-filters'],
                              cwd=session / 'fixture', env=env or environment(), text=True,
                              capture_output=True, timeout=30)
        if proc.returncode:
            raise RuntimeError('RTK isolated initialization failed: ' + proc.stderr)
        return {'exit_code': proc.returncode, 'stdout': proc.stdout, 'stderr': proc.stderr}
    return {}


def session_preflight(session: Path, env: dict, pi_sha256: str, guidance_sha256: str, arm: str) -> dict:
    """Resolve tools in the same non-login zsh and mounts used by model commands.

    This runs before the measured model process and adds no model prompt/call.
    Versions are invoked by absolute resolved paths to avoid command rewriting.
    """
    script = '''import hashlib,json,os,pathlib,shutil,subprocess
result={"tools":{},"guidance":None,"hooks":None,"PATH":os.environ["PATH"]}
for name,args in [("pi-rs",["--version"]),("rtk",["--version"]),("cargo",["--version"]),("rustc",["--version"]),("git",["--version"]),("rg",["--version"]),("python3",["--version"])]:
    path=shutil.which(name)
    if path is None:
        result["tools"][name]=None
        continue
    resolved=pathlib.Path(path).resolve()
    p=subprocess.run([str(resolved),*args],text=True,capture_output=True)
    item={"path":path,"resolved":str(resolved),"version":p.stdout.strip().splitlines()[0] if p.stdout.strip() else p.stderr.strip(),"exit_code":p.returncode}
    if name in ("pi-rs","rtk"):
        item["sha256"]=hashlib.sha256(resolved.read_bytes()).hexdigest()
    result["tools"][name]=item
base=pathlib.Path("/home/aragao/.codex")
agents=base/"AGENTS.md"
if agents.exists(): result["guidance"]={"sha256":hashlib.sha256(agents.read_bytes()).hexdigest(),"bytes":agents.stat().st_size}
hooks=base/"hooks.json"
if hooks.exists(): result["hooks"]=json.loads(hooks.read_text())
print(json.dumps(result))
'''
    command = 'python3 - <<\'PI_BENCH_PREFLIGHT\'\n' + script + '\nPI_BENCH_PREFLIGHT'
    p = subprocess.run(mounts(session) + ['/run/current-system/sw/bin/zsh', '-c', command],
                       cwd=session / 'fixture', env=env, text=True, capture_output=True, timeout=30, check=True)
    result = json.loads(p.stdout)
    if result['tools']['pi-rs']['sha256'] != pi_sha256:
        raise RuntimeError('Candidate binary is shadowed in the session shell PATH.')
    if arm == 'pi' and (not result['guidance'] or result['guidance']['sha256'] != guidance_sha256):
        raise RuntimeError('pi-rs guidance does not match the requested snapshot.')
    if arm == 'stock' and result['guidance']:
        raise RuntimeError('Unexpected native-arm global guidance.')
    if (result['hooks'] is not None) != (arm == 'rtk'):
        raise RuntimeError('Unexpected hook installation state.')
    result['scope'] = 'Pre-model shell probe using identical mounts, env, cwd and non-login zsh; no model tokens. The captured executable snapshot is used for the entire run.'
    return result


def config() -> tuple[list[str], dict]:
    args, public = run.cli_config()
    public.update(model=MODEL, model_reasoning_effort=EFFORT)
    args += ['-c', 'model=' + run.toml_literal(MODEL),
             '-c', 'model_reasoning_effort=' + run.toml_literal(EFFORT)]
    return args, public


def artifacts(session: Path, temp: Path) -> dict:
    log = session / 'share-state/rtk/hook-audit.log'
    audit = run.sanitize(log.read_text(), temp) if log.exists() else ''
    decisions = []
    for line in audit.splitlines():
        fields = line.split(' | ', 3)
        if len(fields) == 4:
            decisions.append(dict(zip(('timestamp', 'action', 'original', 'rewritten'), fields)))
    databases = {}
    for p in sorted((session / 'share-state/rtk').glob('*.db')):
        db = sqlite3.connect('file:' + str(p) + '?mode=ro', uri=True)
        db.row_factory = sqlite3.Row
        tables = {r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        database = {}
        for name in ('commands', 'parse_failures', 'hook_decisions', 'recall_stats', 'recall', 'tee_reads'):
            if name not in tables:
                continue
            records = []
            for row in db.execute('SELECT * FROM ' + name):
                record = dict(row)
                for key, value in list(record.items()):
                    if isinstance(value, bytes):
                        record[key] = {'bytes': len(value), 'sha256': hashlib.sha256(value).hexdigest()}
                    elif isinstance(value, str):
                        record[key] = run.sanitize(value, temp)
                records.append(record)
            database[name] = records
        databases[p.name] = database
        db.close()
    return {'hook_audit': audit, 'hook_decisions': decisions, 'databases': databases,
            'data_files': [str(p.relative_to(session / 'share-state'))
                           for p in sorted((session / 'share-state').rglob('*')) if p.is_file()]}


def parse_result(stdout, task, definition, arm, repeat, elapsed, exit_code, timed_out, rtk):
    events = []
    for line in stdout.splitlines():
        try:
            events.append(json.loads(line))
        except json.JSONDecodeError:
            pass
    usages = [e['usage'] for e in events if e.get('type') == 'turn.completed']
    items = [e['item'] for e in events if e.get('type') == 'item.completed']
    messages = [i['text'] for i in items if i.get('type') == 'agent_message']
    answer = None
    if messages:
        try:
            answer = json.loads(messages[-1])
        except json.JSONDecodeError:
            pass
    commands = [i for i in items if i.get('type') == 'command_execution']
    usage = usages[-1] if usages else None
    history = [r for d in rtk['databases'].values() for r in d.get('commands', [])]
    return {'run_id': f'{task}-{repeat}-{arm}', 'task': task, 'repeat': repeat, 'arm': arm,
            'exit_code': exit_code, 'timed_out': timed_out, 'seconds': elapsed, 'usage': usage,
            'answer': answer, 'correct': answer == definition['expected'],
            'command_count': len(commands), 'commands': [i.get('command') for i in commands],
            'command_exit_codes': [i.get('exit_code') for i in commands],
            'command_output_bytes': sum(len(i.get('aggregated_output', '').encode()) for i in commands),
            'pi_command_count': sum('pi-rs ' in i.get('command', '') for i in commands),
            'rtk_command_count': sum('rtk ' in i.get('command', '') for i in commands),
            'rtk_history_count': len(history),
            'rtk_hook_rewrite_count': sum(d['action'] == 'rewrite' for d in rtk['hook_decisions']),
            'rtk_hook_skip_count': sum(d['action'].startswith('skip:') for d in rtk['hook_decisions']),
            'recovery_command_count': sum('/tee/' in i.get('command', '') or
                                          'rtk recall' in i.get('command', '') or
                                          'rtk proxy' in i.get('command', '') for i in commands),
            'agent_instruction_read_count': sum('/.codex/RTK.md' in i.get('command', '') for i in commands),
            'event_types': sorted(set(e.get('type', '') for e in events)),
            'item_types': sorted(set(i.get('type', '') for i in items)),
            'errors': [i.get('message', '') for i in items if i.get('type') == 'error']}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--repeats', type=int, default=3)
    ap.add_argument('--tasks', nargs='*')
    ap.add_argument('--tag', default='three-way')
    ap.add_argument('--timeout', type=int, default=300)
    ap.add_argument('--pi-binary', type=Path, default=run.PI_BINARY)
    ap.add_argument('--pi-guidance', type=Path, default=run.CODEX_DIRECTORY / 'AGENTS.md')
    ap.add_argument('--toolchain-bin', type=Path, help='Prepend the same explicit toolchain directory in every arm.')
    ap.add_argument('--expect-pi-version', help='Exact required --version output, e.g. "pi-rs 0.3.0".')
    opts = ap.parse_args()
    out = run.HERE / opts.tag
    if out.exists():
        raise SystemExit('Tag exists; completed observations are never silently overwritten.')
    if subprocess.check_output([str(RTK_BINARY), '--version'], text=True).strip() != 'rtk 0.51.0':
        raise SystemExit('RTK version mismatch.')
    temp = Path(tempfile.mkdtemp(prefix='pi-rtk-codex-'))
    pi_source = opts.pi_binary.resolve(strict=True)
    selected_pi = temp / 'binary-snapshot/pi-rs'
    selected_pi.parent.mkdir()
    shutil.copy2(pi_source, selected_pi)
    selected_pi.chmod(0o555)
    pi_sha256 = hashlib.sha256(selected_pi.read_bytes()).hexdigest()
    pi_version = subprocess.check_output([str(selected_pi), '--version'], text=True).strip()
    if opts.expect_pi_version and pi_version != opts.expect_pi_version:
        raise SystemExit('Candidate version mismatch: ' + pi_version)
    toolchain_bin = opts.toolchain_bin.resolve(strict=True) if opts.toolchain_bin else None
    env = environment(selected_pi, toolchain_bin)
    out.mkdir(parents=True)
    tasks = run.task_definitions(temp / 'templates')
    for d in tasks.values():
        d['prompt'] = d['prompt'].replace(run.COMMON_PROMPT, COMMON_PROMPT, 1)
    if opts.tasks:
        tasks = {name: tasks[name] for name in opts.tasks}
    config_args, public = config()
    config_args += ['-c', 'shell_environment_policy.set.PATH=' + run.toml_literal(env['PATH'])]
    public['shell_environment_policy.set.PATH'] = env['PATH']
    guidance_source = opts.pi_guidance.resolve(strict=True)
    guidance = guidance_source.read_bytes()
    guidance_sha256 = hashlib.sha256(guidance).hexdigest()
    run.write(out / 'pi-guidance.md', guidance, stage=True)
    run.write(out / 'rtk-default-awareness.md', (RTK_SOURCE / 'hooks/rtk-awareness.md').read_bytes(), stage=True)
    run.write(out / 'common-prompt.txt', COMMON_PROMPT.rstrip() + '\n', stage=True)
    run.save_json(out / 'tasks.json', tasks)
    manifest = {'started_utc': dt.datetime.now(dt.timezone.utc).isoformat(),
                'codex_version': subprocess.check_output([str(run.CLI), '--version'], text=True).strip(),
                'pi_version': pi_version, 'pi_binary': str(selected_pi),
                'pi_binary_source': str(pi_source), 'pi_binary_sha256': pi_sha256,
                'pi_guidance_source': str(guidance_source), 'guidance_sha256': guidance_sha256,
                'toolchain_bin': str(toolchain_bin) if toolchain_bin else None,
                'rtk_version': 'rtk 0.51.0', 'rtk_binary': str(RTK_BINARY),
                'rtk_binary_sha256': hashlib.sha256(RTK_BINARY.read_bytes()).hexdigest(),
                'rtk_source_commit': 'e001f773f80b22b7dc4c7a79521b30e35aaef026',
                'rtk_awareness_level': 'default', 'rtk_recovery_mode': 'sqlite (unmodified default)',
                'rtk_hook_command': 'rtk hook codex', 'rtk_hooks_enabled_arm': 'rtk only',
                'configuration': public, 'repeats': opts.repeats, 'arms': list(ARMS),
                'isolation': 'bwrap root read-only; /tmp, fresh .codex/.local/share/.config mounts; unchanged HOME/CODEX_HOME; RTK official init in its isolated mount; hook trust bypass only for the RTK arm',
                'environment': {'RTK_TELEMETRY_DISABLED': '1', 'RTK_HOOK_AUDIT': '1',
                                'CARGO_NET_OFFLINE': 'true', 'all_other_RTK_overrides_removed': True},
                'cli_flags': ['exec', '--ignore-user-config', '--ignore-rules', '--ephemeral', '--json',
                              '--color', 'never', '--sandbox', 'workspace-write', '--add-dir', str(SHARE_DIRECTORY)],
                'rtk_extra_flags': ['--dangerously-bypass-hook-trust', '-c', 'features.hooks=true'],
                'order': 'rotate (stock,pi,rtk) by (task_index+repeat_index)%3; every arm occupies each position once per task',
                'working_root': str(temp), 'stop_request_path': str(temp / 'STOP_AFTER_CURRENT'),
                'results': []}
    run.save_json(out / 'manifest.json', manifest)
    for rep in range(opts.repeats):
        for task_index, (task, definition) in enumerate(tasks.items()):
            shift = (rep + task_index) % len(ARMS)
            order = ARMS[shift:] + ARMS[:shift]
            for position, arm in enumerate(order):
                run_id = f'{task}-{rep+1}-{arm}'
                stop_request = temp / 'STOP_AFTER_CURRENT'
                if stop_request.exists():
                    manifest['stopped_utc'] = dt.datetime.now(dt.timezone.utc).isoformat()
                    manifest['stopped_before_run_id'] = run_id
                    manifest['stop_reason'] = stop_request.read_text().strip()
                    run.save_json(out / 'manifest.json', manifest)
                    print('STOPPED', len(manifest['results']), 'before', run_id, flush=True)
                    return
                session = temp / 'runs' / run_id
                shutil.copytree(temp / 'templates' / task, session / 'fixture')
                init = setup(session, arm, guidance, env)
                if init:
                    run.save_json(out / 'rtk-init' / f'{run_id}.json',
                                  {k: run.sanitize(v, temp) if isinstance(v, str) else v for k, v in init.items()})
                    if not (out / 'rtk-installed' / 'hooks.json').exists():
                        for name in ('AGENTS.md', 'RTK.md', 'hooks.json'):
                            run.write(out / 'rtk-installed' / name, (session / 'codex-state' / name).read_bytes(), stage=True)
                        defaults = subprocess.run(mounts(session) + [str(RTK_BINARY), 'config'],
                                                  cwd=session / 'fixture', env=env, text=True,
                                                  capture_output=True, check=True)
                        run.write(out / 'rtk-installed/default-config.txt', run.sanitize(defaults.stdout, temp).rstrip() + '\n', stage=True)
                preflight = session_preflight(session, env, pi_sha256, guidance_sha256, arm)
                run.save_json(out / 'session-preflight' / f'{run_id}.json', preflight)
                run.write(session / 'schema.json', json.dumps(definition['schema']))
                cmd = mounts(session) + [str(run.CLI), '-a', 'never', 'exec', '--ignore-user-config',
                      '--ignore-rules', '--ephemeral', '--json', '--color', 'never', '--sandbox', 'workspace-write',
                      '--add-dir', str(SHARE_DIRECTORY), '-C', str(session / 'fixture'),
                      '--output-schema', str(session / 'schema.json'), *config_args]
                if arm == 'rtk':
                    cmd += ['--dangerously-bypass-hook-trust', '-c', 'features.hooks=true']
                cmd += ['-']
                print('START', run_id, 'position', position + 1, flush=True)
                start = time.perf_counter()
                timed_out = False
                try:
                    p = subprocess.run(cmd, input=definition['prompt'], text=True, capture_output=True,
                                       env=env, timeout=opts.timeout)
                    stdout, stderr, exit_code = p.stdout, p.stderr, p.returncode
                except subprocess.TimeoutExpired as exc:
                    timed_out, exit_code = True, -1
                    stdout, stderr = exc.stdout or b'', exc.stderr or b''
                    stdout = stdout.decode(errors='replace') if isinstance(stdout, bytes) else stdout
                    stderr = stderr.decode(errors='replace') if isinstance(stderr, bytes) else stderr
                elapsed = time.perf_counter() - start
                stdout, stderr = run.sanitize(stdout, temp), run.sanitize(stderr, temp)
                run.write(out / 'transcripts' / f'{run_id}.jsonl', stdout, stage=True)
                run.write(out / 'transcripts' / f'{run_id}.stderr.txt', stderr, stage=True)
                rtk = artifacts(session, temp)
                run.save_json(out / 'rtk-observation' / f'{run_id}.json', rtk)
                result = parse_result(stdout, task, definition, arm, rep+1, elapsed, exit_code, timed_out, rtk)
                result['position'] = position + 1
                manifest['results'].append(result)
                run.save_json(out / 'manifest.json', manifest)
                print('DONE', run_id, 'correct=' + str(result['correct']), 'seconds=' + str(round(elapsed, 2)),
                      'rewrites=' + str(result['rtk_hook_rewrite_count']), 'usage=' + json.dumps(result['usage']), flush=True)
                if result['usage'] is None:
                    raise SystemExit('No usage recorded; investigate before continuing the matrix.')
                if hashlib.sha256(selected_pi.read_bytes()).hexdigest() != pi_sha256:
                    raise SystemExit('Candidate binary changed during the matrix.')
    manifest['finished_utc'] = dt.datetime.now(dt.timezone.utc).isoformat()
    run.save_json(out / 'manifest.json', manifest)
    print('COMPLETE', len(manifest['results']), flush=True)


if __name__ == '__main__':
    main()

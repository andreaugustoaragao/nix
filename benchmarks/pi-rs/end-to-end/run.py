HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
CLI = Path('/home/aragao/.npm-global/bin/codex')
USER_CONFIG = Path('/home/aragao/.codex/config.toml')
CODEX_DIRECTORY = USER_CONFIG.parent
PI_DIRECTORY = Path('/home/aragao/.local/share/pi-rs')

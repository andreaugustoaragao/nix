GIT = shutil.which('git')
COMMON_PROMPT = (
    'Work only with the files in this fixture repository. Do not edit source files. '
    'Do not spawn agents, access external services, use the network, or inspect files '
    'outside this repository, except recovery output files generated by your own commands. '
    'You may run local commands and the existing test suite. '
    'Return only the final JSON object matching the supplied schema. '
)


def write(path: Path, content: str | bytes, *, stage: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content.encode() if isinstance(content, str) else content)
    if stage:
        subprocess.run([GIT, '-C', str(REPO), 'add', '--', str(path)], check=True,
                       stdout=subprocess.DEVNULL)


def save_json(path: Path, value) -> None:
    write(path, json.dumps(value, indent=2, ensure_ascii=False) + '\n', stage=True)


def git(root: Path, *args: str, env=None) -> str:
    return subprocess.check_output([GIT, '-C', str(root), *args], env=env,
                                   stderr=subprocess.DEVNULL, text=True)


def commit(root: Path, message: str, index: int) -> None:
    env = os.environ.copy()
    stamp = f'2026-06-{index + 1:02d}T12:00:00+00:00'
    env.update(GIT_AUTHOR_DATE=stamp, GIT_COMMITTER_DATE=stamp)
    git(root, 'add', '.')
    git(root, 'commit', '-qm', message, env=env)


def initialize(root: Path) -> None:
    root.mkdir(parents=True)
    git(root, 'init', '-q')
    git(root, 'config', 'user.name', 'Fixture Author')
    git(root, 'config', 'user.email', 'fixture@example.invalid')
    git(root, 'config', 'commit.gpgsign', 'false')
    write(root / '.gitignore', 'target/\n')


def schema(properties: dict) -> dict:
    return {'type': 'object', 'properties': properties,
            'required': list(properties), 'additionalProperties': False}


def task_definitions(root: Path) -> dict:
    tasks = {}

    def task(name, prompt, expected, types=None):
        props = {k: {'type': (types or {}).get(k, 'string')} for k in expected}
        tasks[name] = {'prompt': COMMON_PROMPT + prompt, 'expected': expected,
                       'schema': schema(props)}

    p = root / 'noisy_log'
    initialize(p)
    healthy = '2026-06-12T08:42:00Z INFO probe upstream=inventory status=200\n'
    failed = '2026-06-12T08:42:17Z ERROR request failed upstream=inventory code=TLS_CERT_EXPIRED serial=7f:2a\n'
    write(p / 'logs/service.log', healthy * 4000 + failed +
          '2026-06-12T08:42:18Z WARN retry scheduled upstream=inventory delay_ms=500\n' * 2500 +
          '2026-06-12T08:42:21Z INFO probe upstream=inventory status=200\n' * 4000)
    write(p / 'README.md', '# Inventory gateway\nThe incident log is logs/service.log.\n')
    commit(p, 'Add incident capture', 0)
    task('noisy_log', 'Identify the first failed request in logs/service.log: '
         'return its timestamp, upstream, and error_code exactly as recorded.',
         {'timestamp': '2026-06-12T08:42:17Z', 'upstream': 'inventory',
          'error_code': 'TLS_CERT_EXPIRED'})

    p = root / 'config_diff'
    initialize(p)
    for i in range(120):
        write(p / f'config/services/service_{i:03d}.toml',
              f'name = "service-{i:03d}"\nport = {8100+i}\nauth_required = true\n'
              'request_timeout_ms = 3000\n# build stamp: 2026.06.01\n')
    write(p / 'README.md', '# Deployment configuration\nAll services must require authentication.\n'
          'Build stamp comments have no runtime effect.\n')
    commit(p, 'Initial authenticated service configuration', 0)
    for i in range(120):
        f = p / f'config/services/service_{i:03d}.toml'
        s = f.read_text().replace('2026.06.01', '2026.06.12')
        if i == 57:
            s = s.replace('auth_required = true', 'auth_required = false')
        f.write_text(s)
    task('config_diff', 'Review the uncommitted deployment configuration changes against '
         'the repository requirements. Ignore build stamp comment changes. Identify the '
         'single behavior regression; return file, setting, before, and after. '
         'Represent before and after as strings.',
         {'file': 'config/services/service_057.toml', 'setting': 'auth_required',
          'before': 'true', 'after': 'false'})

    p = root / 'source_lookup'
    initialize(p)
    write(p / 'src/client.py', '''from dataclasses import dataclass

@dataclass(frozen=True)
class ClientPolicy:
    timeout_ms: int = 1800
    retries: int = 2

DEFAULT_POLICY = ClientPolicy()
CHECKOUT_POLICY = ClientPolicy(timeout_ms=4200, retries=3)
REPORTING_POLICY = ClientPolicy(timeout_ms=15000, retries=1)

def policy_for(service: str) -> ClientPolicy:
    return {"checkout": CHECKOUT_POLICY, "reporting": REPORTING_POLICY}.get(service, DEFAULT_POLICY)
''')
    for i in range(18):
        write(p / f'src/component_{i:02d}.py',
              f'"""Component {i}: uses the shared client policy."""\n'
              'from .client import policy_for\n\n'
              f'def component_{i}_timeout():\n    return policy_for("component-{i}").timeout_ms\n')
    write(p / 'README.md', '# Service client\nShared policies are defined under src.\n')
    commit(p, 'Add shared client policies', 0)
    task('source_lookup', 'Without executing application code, determine the checkout '
         'client timeout in milliseconds and its retry count from source; return '
         'timeout_ms and retries as integers.', {'timeout_ms': 4200, 'retries': 3},
         {'timeout_ms': 'integer', 'retries': 'integer'})

    p = root / 'cargo_failure'
    initialize(p)
    write(p / 'Cargo.toml', '[package]\nname = "billing-fixture"\nversion = "0.1.0"\nedition = "2021"\n')
    source = '''pub fn subtotal(quantity: u64, unit_price: u64) -> u64 {
    quantity * unit_price
}

pub fn total_with_shipping(quantity: u64, unit_price: u64) -> u64 {
    subtotal(quantity, unit_price) + 6
}

#[cfg(test)]
mod tests {
    use super::*;
'''
    for i in range(240):
        source += f'    #[test]\n    fn subtotal_case_{i:03d}() {{ assert_eq!(subtotal({i}, 3), {i*3}); }}\n'
    source += '''    #[test]
    fn shipping_total_for_three_items() {
        assert_eq!(total_with_shipping(3, 7), 25);
    }
}
'''
    write(p / 'src/lib.rs', source)
    write(p / 'README.md', '# Billing calculator\nRun the Rust test suite with Cargo.\n'
          'There are no third party dependencies. Shipping is a flat 4 currency units.\n')
    commit(p, 'Add billing calculator and tests', 0)
    task('cargo_failure', 'Run the existing Rust test suite. Report the failing test '
         'name without module prefix, actual numeric assertion value, expected numeric '
         'assertion value, number of passed tests, and number of failed tests. Do not fix it.',
         {'test': 'shipping_total_for_three_items', 'actual': 27, 'expected': 25,
          'passed': 240, 'failed': 1},
         {'actual': 'integer', 'expected': 'integer', 'passed': 'integer', 'failed': 'integer'})

    p = root / 'recent_history'
    initialize(p)
    write(p / 'config/cache.toml', 'ttl_seconds = 30\n')
    write(p / 'README.md', '# Cache service\nDeployment notes are in notes/.\n')
    commit(p, 'Initial cache configuration', 0)
    messages = ['docs: clarify health probe', 'build: refresh package metadata',
                'cache: increase TTL to reduce origin load', 'docs: update release checklist',
                'metrics: document cache hit ratio', 'build: normalize labels',
                'docs: clarify owner rotation', 'ops: document rollback procedure']
    changed_commit = ''
    for i, msg in enumerate(messages, start=1):
        write(p / f'notes/update_{i:02d}.md', f'# Update {i}\n{msg}\n')
        if i == 3:
            write(p / 'config/cache.toml', 'ttl_seconds = 120\n')
        commit(p, msg, i)
        if i == 3:
            changed_commit = git(p, 'rev-parse', '--short=7', 'HEAD').strip()
    task('recent_history', 'Find the most recent Git commit that changed the cache TTL '
         'setting. Return its seven-character commit hash, exact subject, prior TTL, '
         'and current TTL (TTL values as integer seconds).',
         {'commit': changed_commit, 'subject': messages[2], 'before': 30, 'after': 120},
         {'before': 'integer', 'after': 'integer'})

    return tasks


def toml_literal(value) -> str:
    if isinstance(value, dict):
        return '{' + ', '.join(json.dumps(k) + '=' + toml_literal(v)
                               for k, v in value.items()) + '}'
    if isinstance(value, list):
        return '[' + ', '.join(map(toml_literal, value)) + ']'
    return json.dumps(value)


def cli_config() -> tuple[list[str], dict]:
    current = tomllib.loads(USER_CONFIG.read_text())
    provider = current['model_provider']
    selected = current['model_providers'][provider]
    conf = {
        'model': current['model'],
        'model_reasoning_effort': current['model_reasoning_effort'],
        'model_provider': provider,
        f'model_providers.{provider}': selected,
        'project_doc_max_bytes': 0,
        'allow_login_shell': False,
        'skills.include_instructions': False,
        'features.skip_host_skill_discovery': True,
        'features.hooks': False,
        'features.plugin_hooks': False,
        'features.plugins': False,
        'features.apps': False,
        'features.memories': False,
        'features.multi_agent': False,
        'features.multi_agent_v2': False,
        'features.shell_snapshot': False,
        'features.shell_snapshot_v2': False,
        'web_search': 'disabled',
        'suppress_unstable_features_warning': True,
        'sandbox_workspace_write.network_access': False,
    }
    args = []
    for k, v in conf.items():
        args += ['-c', k + '=' + toml_literal(v)]
    public = {k: v for k, v in conf.items() if not k.startswith('model_providers.')}
    public['provider_details'] = 'Inherited selected provider/auth command; endpoint and credential details omitted.'
    return args, public


def sanitize(text: str, private_root: Path) -> str:
    text = text.replace(str(private_root), '<run-root>')
    text = re.sub(r'https?://[^\s"<>]+', '<redacted-url>', text)
    text = re.sub(r'(?i)(authorization[=: ]+bearer\s+)\S+', r'\1<redacted>', text)
    return text


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--repeats', type=int, default=3)
    ap.add_argument('--tasks', nargs='*')
    ap.add_argument('--tag', default='main')
    ap.add_argument('--timeout', type=int, default=300)
    args = ap.parse_args()
    output = HERE / args.tag
    if output.exists():
        raise SystemExit('Output tag already exists; do not silently overwrite completed sessions.')
    temp = Path(tempfile.mkdtemp(prefix='pi-rs-codex-ab-'))
    output.mkdir(parents=True)
    tasks = task_definitions(temp / 'templates')
    if args.tasks:
        tasks = {name: tasks[name] for name in args.tasks}
    config_args, public_config = cli_config()
    guidance = (CODEX_DIRECTORY / 'AGENTS.md').read_bytes()
    write(output / 'pi-guidance.md', guidance, stage=True)
    write(output / 'common-prompt.txt', COMMON_PROMPT.rstrip() + '\n', stage=True)
    save_json(output / 'tasks.json', tasks)
    manifest = {'started_utc': dt.datetime.now(dt.timezone.utc).isoformat(),
                'codex_version': subprocess.check_output([str(CLI), '--version'], text=True).strip(),
                'pi_version': subprocess.check_output([str(PI_BINARY), '--version'], text=True).strip(),
                'pi_binary': str(PI_BINARY), 'guidance_sha256': hashlib.sha256(guidance).hexdigest(),
                'configuration': public_config, 'repeats': args.repeats,
                'isolation': 'bwrap: root read-only, /tmp writable, temporary .codex and pi-rs data mounts; unchanged HOME/CODEX_HOME; ignore user config and execpolicy rules; no inherited instructions except treatment AGENTS.md',
                'cli_flags': ['exec', '--ignore-user-config', '--ignore-rules', '--ephemeral',
                              '--json', '--color', 'never', '--sandbox', 'workspace-write',
                              '--add-dir', str(PI_DIRECTORY)],
                'order': 'task order fixed; first arm alternates per task and repetition',
                'working_root': str(temp), 'results': []}
    # The temporary path is operational provenance, not part of a model prompt.
    save_json(output / 'manifest.json', manifest)
    env = {k: v for k, v in os.environ.items()
           if not k.startswith(('CODEX_', 'NOISE_', 'OPENAI_')) or k == 'CODEX_HOME'}
    env['PATH'] = str(PI_BINARY.parent) + ':' + env['PATH']
    env['RUST_LOG'] = 'error'
    env['GIT_TERMINAL_PROMPT'] = '0'
    env['CARGO_NET_OFFLINE'] = 'true'
    for repeat in range(args.repeats):
        for task_index, (name, definition) in enumerate(tasks.items()):
            arms = ['stock', 'pi'] if (repeat + task_index) % 2 == 0 else ['pi', 'stock']
            for arm in arms:
                run_id = f'{name}-{repeat+1}-{arm}'
                session = temp / 'runs' / run_id
                fixture = session / 'fixture'
                shutil.copytree(temp / 'templates' / name, fixture)
                codex_state = session / 'codex-state'
                codex_state.mkdir()
                pi_state = session / 'pi-state'
                pi_state.mkdir()
                if arm == 'pi':
                    write(codex_state / 'AGENTS.md', guidance)
                write(session / 'schema.json', json.dumps(definition['schema']))
                cmd = [shutil.which('bwrap'), '--die-with-parent', '--ro-bind', '/', '/',
                       '--bind', '/tmp', '/tmp', '--proc', '/proc', '--dev-bind', '/dev', '/dev',
                       '--bind', str(codex_state), str(CODEX_DIRECTORY),
                       '--bind', str(pi_state), str(PI_DIRECTORY), '--', str(CLI),
                       '-a', 'never', 'exec', '--ignore-user-config', '--ignore-rules',
                       '--ephemeral', '--json', '--color', 'never', '--sandbox', 'workspace-write',
                       '--add-dir', str(PI_DIRECTORY),
                       '-C', str(fixture), '--output-schema', str(session / 'schema.json'),
                       *config_args, '-']
                print('START', run_id, flush=True)
                start = time.perf_counter()
                timed_out = False
                try:
                    proc = subprocess.run(cmd, input=definition['prompt'], text=True,
                                          capture_output=True, env=env, timeout=args.timeout)
                    stdout, stderr, exit_code = proc.stdout, proc.stderr, proc.returncode
                except subprocess.TimeoutExpired as e:
                    timed_out = True
                    stdout = e.stdout or b''
                    stderr = e.stderr or b''
                    stdout = stdout.decode(errors='replace') if isinstance(stdout, bytes) else stdout
                    stderr = stderr.decode(errors='replace') if isinstance(stderr, bytes) else stderr
                    exit_code = -1
                elapsed = time.perf_counter() - start
                stdout, stderr = sanitize(stdout, temp), sanitize(stderr, temp)
                write(output / 'transcripts' / f'{run_id}.jsonl', stdout, stage=True)
                write(output / 'transcripts' / f'{run_id}.stderr.txt', stderr, stage=True)
                events = []
                for line in stdout.splitlines():
                    try:
                        events.append(json.loads(line))
                    except json.JSONDecodeError:
                        pass
                usages = [e['usage'] for e in events if e.get('type') == 'turn.completed']
                items = [e['item'] for e in events if e.get('type') == 'item.completed']
                messages = [i['text'] for i in items if i.get('type') == 'agent_message']
                answer = None
                if messages:
                    try:
                        answer = json.loads(messages[-1])
                    except json.JSONDecodeError:
                        pass
                commands = [i for i in items if i.get('type') == 'command_execution']
                usage = usages[-1] if usages else None
                result = {'run_id': run_id, 'task': name, 'repeat': repeat + 1, 'arm': arm,
                          'exit_code': exit_code, 'timed_out': timed_out, 'seconds': elapsed,
                          'usage': usage, 'answer': answer, 'correct': answer == definition['expected'],
                          'command_count': len(commands),
                          'commands': [i.get('command') for i in commands],
                          'command_output_bytes': sum(len(i.get('aggregated_output', '').encode()) for i in commands),
                          'pi_command_count': sum('pi-rs ' in i.get('command', '') for i in commands),
                          'recovery_command_count': sum('/tee/' in i.get('command', '') for i in commands),
                          'event_types': sorted(set(e.get('type', '') for e in events)),
                          'item_types': sorted(set(i.get('type', '') for i in items))}
                manifest['results'].append(result)
                save_json(output / 'manifest.json', manifest)
                print('DONE', run_id, 'correct=' + str(result['correct']),
                      'seconds=' + str(round(elapsed, 2)), 'usage=' + json.dumps(usage), flush=True)
                if usage is None:
                    raise SystemExit('Session produced no usage; inspect sanitized pilot artifacts before continuing.')
    manifest['finished_utc'] = dt.datetime.now(dt.timezone.utc).isoformat()
    save_json(output / 'manifest.json', manifest)
    print('COMPLETE', len(manifest['results']), 'sessions', flush=True)


if __name__ == '__main__':
    main()

"""Paired isolated Codex sessions; no provider secrets are written to artifacts.

Uses the installed CLI directly and a Linux mount namespace, never changing
HOME/CODEX_HOME or the user's actual configuration. Fixtures are synthetic,
deterministic, and independent of pi-rs. See README.md for measurement limits.
"""

